import { spawnSync } from 'node:child_process'
import { copyFile, lstat, mkdir, mkdtemp, readFile, readdir, rename, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { basename, dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const pinnedGeneratorImage = 'openapitools/openapi-generator-cli:v7.26.0'
const imageOverrideVariable = 'OPENAPI_GENERATOR_SERVER_IMAGE'
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const generatedDirectory = resolve(projectRoot, 'backend/internal/httpapi/generated')
const expectedGeneratedDirectory = join(projectRoot, 'backend', 'internal', 'httpapi', 'generated')
const inputSpecification = join(projectRoot, 'api/tsp-output/openapi.yaml')
const generatorConfig = join(projectRoot, 'api/openapi-generator-server.yaml')
const generatedMarker = '// Code generated by OpenAPI Generator'

function fail(message) {
  throw new Error(message)
}

function run(command, args, description) {
  const result = spawnSync(command, args, { cwd: projectRoot, stdio: 'inherit' })

  if (result.error) {
    throw result.error
  }
  if (result.status !== 0) {
    fail(`${description} exited with status ${result.status}`)
  }
}

async function pathExists(path) {
  try {
    await lstat(path)
    return true
  } catch (error) {
    if (error.code === 'ENOENT') {
      return false
    }
    throw error
  }
}

async function collectFiles(directory, relativeDirectory = '') {
  const files = new Map()
  const currentDirectory = join(directory, relativeDirectory)
  let entries

  try {
    entries = await readdir(currentDirectory, { withFileTypes: true })
  } catch (error) {
    if (error.code === 'ENOENT') {
      return files
    }
    throw error
  }

  for (const entry of entries) {
    const relativePath = join(relativeDirectory, entry.name)

    if (entry.isDirectory()) {
      const nestedFiles = await collectFiles(directory, relativePath)
      for (const [path, contents] of nestedFiles) {
        files.set(path, contents)
      }
    } else if (entry.isFile()) {
      files.set(relativePath, await readFile(join(directory, relativePath)))
    }
  }

  return files
}

async function generatedGoFiles(directory) {
  const files = await collectFiles(directory)
  const goFiles = [...files.keys()].filter((path) => path.endsWith('.go')).sort()

  if (goFiles.length === 0) {
    fail('OpenAPI Generator did not create any Go files')
  }
  for (const path of goFiles) {
    if (dirname(path) !== '.') {
      fail(`Unexpected nested generated Go file: ${path}`)
    }
    if (!files.get(path).toString().startsWith(generatedMarker)) {
      fail(`Generated-code marker is missing from ${path}`)
    }
  }

  return goFiles
}

function generatorImage() {
  const override = process.env[imageOverrideVariable]

  if (process.env.CI && override && override !== pinnedGeneratorImage) {
    fail(`${imageOverrideVariable} may override the pinned image only for local diagnostics`)
  }

  return override || pinnedGeneratorImage
}

function generate(outputDirectory) {
  const dockerArguments = ['run', '--rm']

  if (typeof process.getuid === 'function' && typeof process.getgid === 'function') {
    dockerArguments.push('--user', `${process.getuid()}:${process.getgid()}`)
  }

  dockerArguments.push(
    '--volume',
    `${projectRoot}:/local:ro`,
    '--volume',
    `${outputDirectory}:/out`,
    generatorImage(),
    'generate',
    '--config',
    '/local/api/openapi-generator-server.yaml',
    '--input-spec',
    '/local/api/tsp-output/openapi.yaml',
    '--output',
    '/out',
  )

  run('docker', dockerArguments, 'OpenAPI Generator')
}

async function prepareGeneratedPackage(generatorOutput, packageDirectory) {
  const goFiles = await generatedGoFiles(generatorOutput)

  await mkdir(packageDirectory, { recursive: true })
  for (const path of goFiles) {
    await copyFile(join(generatorOutput, path), join(packageDirectory, basename(path)))
  }

  run('gofmt', ['-w', ...goFiles.map((path) => join(packageDirectory, basename(path)))], 'gofmt')
}

async function differencesBetween(committedDirectory, generatedPackageDirectory) {
  const committedFiles = await collectFiles(committedDirectory)
  const generatedFiles = await collectFiles(generatedPackageDirectory)
  const paths = new Set([...committedFiles.keys(), ...generatedFiles.keys()])

  return [...paths]
    .filter((path) => {
      const committed = committedFiles.get(path)
      const generated = generatedFiles.get(path)

      return !committed || !generated || !committed.equals(generated)
    })
    .map((path) => path.split(sep).join('/'))
    .sort()
}

async function replaceGeneratedDirectory(stagedDirectory) {
  if (generatedDirectory !== expectedGeneratedDirectory) {
    fail(`Refusing to replace unexpected path: ${generatedDirectory}`)
  }

  const parentDirectory = dirname(generatedDirectory)
  const backupDirectory = join(
    parentDirectory,
    `.generated-server-backup-${process.pid}-${Date.now()}`,
  )
  const targetExists = await pathExists(generatedDirectory)

  if (targetExists) {
    const target = await lstat(generatedDirectory)
    if (!target.isDirectory() || target.isSymbolicLink()) {
      fail(`Refusing to replace non-directory target: ${generatedDirectory}`)
    }
    await rename(generatedDirectory, backupDirectory)
  }

  try {
    await rename(stagedDirectory, generatedDirectory)
  } catch (error) {
    if (targetExists) {
      await rename(backupDirectory, generatedDirectory)
    }
    throw error
  }

  if (targetExists) {
    await rm(backupDirectory, { force: true, recursive: true })
  }
}

const [mode, ...extraArguments] = process.argv.slice(2)
if (!['--write', '--check'].includes(mode) || extraArguments.length > 0) {
  console.error('Usage: node scripts/generate-server.mjs --write|--check')
  process.exit(2)
}

if (!(await pathExists(inputSpecification))) {
  fail(`OpenAPI input is missing: ${relative(projectRoot, inputSpecification)}`)
}
if (!(await pathExists(generatorConfig))) {
  fail(`Generator config is missing: ${relative(projectRoot, generatorConfig)}`)
}

const temporaryDirectory = await mkdtemp(join(tmpdir(), 'call-calendar-server-'))
const generatorOutput = join(temporaryDirectory, 'generator-output')
const generatedPackage = join(temporaryDirectory, 'generated')
let stagedDirectory

try {
  await mkdir(generatorOutput)
  generate(generatorOutput)
  await prepareGeneratedPackage(generatorOutput, generatedPackage)

  if (mode === '--check') {
    const differences = await differencesBetween(generatedDirectory, generatedPackage)
    if (differences.length > 0) {
      console.error('Generated server package is out of date. Run `make generate-server`.')
      for (const path of differences) {
        console.error(`- ${path}`)
      }
      process.exitCode = 1
    }
  } else {
    const parentDirectory = dirname(generatedDirectory)
    stagedDirectory = await mkdtemp(join(parentDirectory, '.generated-server-staging-'))
    await prepareGeneratedPackage(generatorOutput, stagedDirectory)
    await replaceGeneratedDirectory(stagedDirectory)
    stagedDirectory = undefined
    console.log(
      `Generated ${relative(projectRoot, generatedDirectory)} with ${
        (await generatedGoFiles(generatedDirectory)).length
      } Go files.`,
    )
  }
} finally {
  if (stagedDirectory) {
    await rm(stagedDirectory, { force: true, recursive: true })
  }
  await rm(temporaryDirectory, { force: true, recursive: true })
}
